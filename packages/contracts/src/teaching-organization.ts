import { z } from 'zod';
const text = z.string().trim().min(1).max(100),
  id = z.string().min(1).max(100);
export const OrganizationCommand = z.discriminatedUnion('operation', [
  z.object({
    operation: z.literal('create-school'),
    name: text,
    administratorName: text,
    proof: z.string(),
  }),
  z.object({ operation: z.literal('rename-school'), id, name: text, proof: z.string() }),
  z.object({
    operation: z.literal('create-school-admin'),
    schoolId: id,
    name: text,
    proof: z.string(),
  }),
  z.object({ operation: z.literal('create-offering'), schoolId: id, courseId: id, term: text }),
  z.object({
    operation: z.literal('update-course'),
    schoolId: id,
    courseId: id,
    title: text.optional(),
    code: text.optional(),
    archived: z.boolean().optional(),
  }),
  z.object({
    operation: z.literal('update-offering'),
    schoolId: id,
    offeringId: id,
    term: text.optional(),
    archived: z.boolean().optional(),
  }),
  z.object({ operation: z.literal('create-teacher'), schoolId: id, name: text }),
  z.object({
    operation: z.literal('create-course'),
    schoolId: id,
    title: text,
    code: text,
  }),
  z.object({
    operation: z.literal('create-class'),
    schoolId: id,
    offeringId: id,
    name: text,
    teacherId: id,
  }),
  z.object({
    operation: z.literal('upsert-student'),
    schoolId: id,
    name: text,
    studentNumber: text,
    classIds: z.array(id).max(50),
  }),
  z.object({
    operation: z.literal('reset-password'),
    schoolId: id.optional(),
    id,
    proof: z.string(),
  }),
  z.object({
    operation: z.literal('update-account'),
    schoolId: id.optional(),
    id,
    proof: z.string(),
    name: text.optional(),
    studentNumber: text.optional(),
    active: z.boolean().optional(),
  }),
  z.object({
    operation: z.literal('set-school-active'),
    id,
    active: z.boolean(),
    proof: z.string(),
  }),
  z.object({
    operation: z.literal('membership'),
    schoolId: id.optional(),
    classId: id,
    studentId: id,
    joined: z.boolean(),
  }),
  z.object({
    operation: z.literal('update-class'),
    schoolId: id.optional(),
    fromTeacherId: id.optional(),
    name: text.optional(),
    classId: id,
    teacherId: id.optional(),
    archived: z.boolean().optional(),
    proof: z.string(),
  }),
]);
